def safe_dataframe(data):
    df = data.copy() if isinstance(data, pd.DataFrame) else pd.DataFrame(data)
    # Streamlit/PyArrow cannot reliably infer mixed bool/string columns.
    if "Available" in df.columns:
        df["Available"] = df["Available"].astype(str)
    return df


def show_df(data):
    df = safe_dataframe(data)
    st.dataframe(df, width="stretch", hide_index=True)


def audit(actor, action=None, details=None):
    """Support both audit(actor, action, details) and legacy audit(action, details)."""
    try:
        if details is None:
            details = action or ""
            action = actor
            actor = st.session_state.get("role") or "SYSTEM"
        add_audit(str(actor), str(action), str(details))
    except Exception as exc:
        st.warning(f"Audit entry warning: {exc}")


def create_secureland_pdf(title, content):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )
    styles = getSampleStyleSheet()
    story = [
        Paragraph("CyberBridge Digital Solutions Pune", styles["Title"]),
        Paragraph("Bridging Technology, Security &amp; Digital Trust", styles["Normal"]),
        Spacer(1, 0.2 * inch),
        Paragraph(escape(str(title)), styles["Heading1"]),
        Spacer(1, 0.15 * inch),
        Paragraph("Mobile: 9423174649 | Email: cyberbridgedigital@gmail.com", styles["Normal"]),
        Spacer(1, 0.2 * inch)
    ]
    for line in str(content).splitlines():
        story.append(Paragraph(escape(line) if line else "&nbsp;", styles["Normal"]))
        story.append(Spacer(1, 5))
    story.extend([
        Spacer(1, 0.2 * inch),
        Paragraph(
            "Generated by SecureLand Prototype. This report is a technical system output "
            "and is not a government-certified or independent forensic opinion.",
            styles["Italic"]
        )
    ])
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


