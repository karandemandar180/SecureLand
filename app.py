def get_configured_password(secret_name):

    value = None

    try:
        value = st.secrets.get(secret_name)
    except Exception:
        pass

    if not value:
        value = os.getenv(secret_name)

    return str(value).strip() if value else ""


def is_strong_password(password):

    return (
        len(password) >= 12
        and any(c.isupper() for c in password)
        and any(c.islower() for c in password)
        and any(c.isdigit() for c in password)
        and any(not c.isalnum() for c in password)
    )


PASSWORDS = {
    "Admin": get_configured_password(
        "SECURELAND_ADMIN_PASSWORD"
    ),
    "Talathi": get_configured_password(
        "SECURELAND_TALATHI_PASSWORD"
    ),
    "Citizen": get_configured_password(
        "SECURELAND_CITIZEN_PASSWORD"
    )
}

missing_roles = [
    r for r, p in PASSWORDS.items() if not p
]

weak_roles = [
    r for r, p in PASSWORDS.items()
    if p and not is_strong_password(p)
]

if missing_roles or weak_roles:

    st.error(
        "SecureLand login configuration is incomplete."
    )

    if missing_roles:
        st.warning(
            "Password missing: " + ", ".join(missing_roles)
        )

    if weak_roles:
        st.warning(
            "Weak password: " + ", ".join(weak_roles)
        )

    st.info(
        "Configure strong passwords in "
        ".streamlit/secrets.toml or environment variables."
    )

    st.stop()


