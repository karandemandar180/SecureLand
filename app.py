def create_secureland_pdf(title, content):

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    story = [
        Paragraph(
            "CyberBridge Digital Solutions Pune",
            styles["Title"]
        ),
        Paragraph(
            "Bridging Technology, Security &amp; Digital Trust",
            styles["Normal"]
        ),
        Spacer(1, 0.2 * inch),
        Paragraph(
            escape(str(title)),
            styles["Heading1"]
        ),
        Spacer(1, 0.15 * inch),
        Paragraph(
            "Mobile: 9423174649 | Email: cyberbridgedigital@gmail.com",
            styles["Normal"]
        ),
        Spacer(1, 0.2 * inch)
    ]

    for line in str(content).splitlines():

        story.append(
            Paragraph(
                escape(line) if line else "&nbsp;",
                styles["Normal"]
            )
        )

        story.append(Spacer(1, 5))

    story.append(
        Paragraph(
            "Generated by SecureLand Prototype. "
            "This is not a government-certified or independent forensic opinion.",
            styles["Italic"]
        )
    )

    doc.build(story)
    buffer.seek(0)

    return buffer.getvalue()


